# Functions
# ──────────────────────────────────────────────

def identify_waf(headers, body_text, status_code):
    """Try to identify which WAF is deployed based on response.

    Returns list of (name, confidence) tuples.
    """
    matches = []
    for name, sig in WAF_SIGNATURES.items():
        score = 0
        total = 0

        for header, pattern in sig["headers"].items():
            total += 1
            val = headers.get(header, "")
            if val:
                if pattern:
                    if re.search(pattern, val, re.I):
                        score += 1
                else:
                    score += 1

        for cookie, pattern in sig["cookies"].items():
            total += 1
            raw = headers.get("set-cookie", "")
            if raw and cookie in raw:
                if pattern:
                    if re.search(pattern, raw, re.I):
                        score += 1
                else:
                    score += 1

        for body_pat in sig["body"]:
            total += 1
            if re.search(body_pat, body_text, re.I):
                score += 1

        if total > 0 and score > 0:
            confidence = score / total
            matches.append((name, round(confidence, 2)))

    matches.sort(key=lambda x: -x[1])
    return matches


def is_blocked(response):
    """Determine whether the WAF blocked the request."""
    text = response.text.lower()

    # Status code check
    if response.status_code in BLOCK_STATUS_CODES:
        return True

    # Keyword check
    for kw in BLOCK_KEYWORDS:
        if kw in text:
            return True

    # Response length anomaly
    # (if response is very short / generic, it's likely a block page)
    if response.status_code != 200 and len(text) < 500:
        return True

    return False


def block_reason(response):
    """Return a short string describing why a request was blocked."""
    if response.status_code in (403,):
        return f"HTTP {response.status_code} Forbidden"
    if response.status_code == 406:
        return "HTTP 406 Not Acceptable"
    if response.status_code == 429:
        return "HTTP 429 Rate Limited"
    if response.status_code in (503, 493, 494, 495):
        return f"HTTP {response.status_code}"
    if response.status_code == 501:
        return "HTTP 501 Not Implemented"

    text = response.text.lower()
    for kw in BLOCK_KEYWORDS:
        if kw in text:
            return kw[:50]

    return f"HTTP {response.status_code} (short page)"
